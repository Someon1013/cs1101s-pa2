def alternating_total(xs):
    total = 0
    sign = 1
    while not is_none(xs):
        total = total + sign * head(xs)
        sign = -sign
        xs = tail(xs)
    return total

pa_check(alternating_total(None) == 0, "Empty checksum")
pa_check(alternating_total(llist(5, 2, -4, 3)) == -4, "Alternate by position")
pa_check(alternating_total(llist(-7)) == -7, "Singleton")
